#!/usr/bin/env python3
"""Generate the single-file edition of the Ubuntu weak lab.

    python3 build_onefile.py            # writes vedha-weak-lab.sh next to this file

The single file = ubuntu-weak-lab.sh + lab_emulators.py + lab_probe.py (embedded), with
Critical + High as the ONLY severities it can build and no safe controls by default.
Regenerate after changing any of the three source files; do not hand-edit the output.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "vedha-weak-lab.sh")


def read(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as fh:
        return fh.read()


def must_replace(text, old, new, count=1):
    if old not in text:
        sys.exit(f"build_onefile: expected text not found:\n{old[:120]}")
    return text.replace(old, new, count)


def main():
    base = read("ubuntu-weak-lab.sh")
    emu = read("lab_emulators.py")
    probe = read("lab_probe.py")
    for tag, body in (("VEDHA_EMU_PY", emu), ("VEDHA_PROBE_PY", probe)):
        if tag in body:
            sys.exit(f"heredoc delimiter {tag} appears inside the embedded file")

    s = base
    # banner right after the shebang
    first, rest = s.split("\n", 1)
    banner = ("# SINGLE-FILE EDITION (generated by build_onefile.py - do not hand-edit).\n"
              "# Builds ONLY Critical and High scenarios, on Ubuntu 22.04/24.04. Needs no other files:\n"
              "# the emulators and the independent verifier are embedded below.\n")
    s = first + "\n" + banner + rest

    # Critical + High only; no controls by default
    s = must_replace(s, 'MIN_SEV="medium"; WITH_CONTROLS=1; PURGE=0',
                     'MIN_SEV="high"; WITH_CONTROLS=0; PURGE=0')
    s = must_replace(s, 'case "$MIN_SEV" in medium) MIN_RANK=1 ;; high) MIN_RANK=2 ;; critical) MIN_RANK=3 ;; *) die "--min-severity: medium|high|critical" ;; esac',
                     'case "$MIN_SEV" in high) MIN_RANK=2 ;; critical) MIN_RANK=3 ;; *) die "--min-severity: high|critical (this edition builds nothing below High)" ;; esac')
    s = must_replace(s, '--no-controls) WITH_CONTROLS=0 ;;',
                     '--no-controls) WITH_CONTROLS=0 ;;\n      --with-controls) WITH_CONTROLS=1 ;;')
    s = must_replace(s, 'EXCLUDED_NOTE="Excluded as Low/Info by design: T06 LDAP anonymous bind, T09 DNS version.bind, T17 no HSTS, T29 excessive admins, GTP, NTRIP."',
                     'EXCLUDED_NOTE="Not built by this edition: every Medium, Low and Info scenario (Critical and High only)."')

    s = must_replace(s, "--min-severity medium|high|critical", "--min-severity high|critical")
    s = must_replace(s, "--verify-host IP  --no-controls", "--verify-host IP  --with-controls (safe twins, off by default)")
    # embedded helpers instead of copying sibling files
    s = must_replace(s, '  install -m 0755 "$SRC_DIR/lab_emulators.py" "$LAB_DIR/lab_emulators.py"\n'
                        '  install -m 0755 "$SRC_DIR/lab_probe.py" "$LAB_DIR/lab_probe.py"\n',
                     '  write_helpers\n')
    helpers = ("write_helpers() { # the two helper programs, embedded so this file is self-contained\n"
               "  cat >\"$LAB_DIR/lab_emulators.py\" <<'VEDHA_EMU_PY'\n" + emu.rstrip("\n") + "\nVEDHA_EMU_PY\n"
               "  cat >\"$LAB_DIR/lab_probe.py\" <<'VEDHA_PROBE_PY'\n" + probe.rstrip("\n") + "\nVEDHA_PROBE_PY\n"
               "  chmod 0755 \"$LAB_DIR/lab_emulators.py\" \"$LAB_DIR/lab_probe.py\"\n"
               "}\n\n")
    s = must_replace(s, "usage() {", helpers + "usage() {")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(s)
    os.chmod(OUT, 0o755)
    print(f"wrote {OUT} ({len(s.splitlines())} lines)")


if __name__ == "__main__":
    main()
