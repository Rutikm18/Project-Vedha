"""
write_sealed_consts.py — generate agent/_sealed.py for a sealed build.

Run by Dockerfile.sealed before Nuitka compiles, with the build args:

    python3 tools/write_sealed_consts.py --pubkey <hex> [--hw-fingerprint <hex>]

Values are validated and written with repr(), so a build arg can never inject
code into the compiled module.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

_HEX = re.compile(r"[0-9a-f]+")


def render(pubkey_hex: str, hw_fingerprint: str = "") -> str:
    pub = (pubkey_hex or "").strip().lower()
    fp = (hw_fingerprint or "").strip().lower()
    if len(pub) != 64 or not _HEX.fullmatch(pub):
        raise ValueError("a sealed build needs the vendor Ed25519 public key as 64 hex chars")
    if fp and (len(fp) != 32 or not _HEX.fullmatch(fp)):
        raise ValueError("the hardware fingerprint must be 32 hex chars (or empty = not host-locked)")
    return (
        '"""Generated by tools/write_sealed_consts.py for a sealed build — do not edit."""\n'
        "SEALED = True\n"
        f"LICENSE_PUBKEY_HEX = {pub!r}\n"
        f"HW_BIND_FINGERPRINT = {fp!r}\n"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--pubkey", required=True)
    ap.add_argument("--hw-fingerprint", default="")
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "agent" / "_sealed.py"))
    args = ap.parse_args(argv)
    try:
        text = render(args.pubkey, args.hw_fingerprint)
    except ValueError as exc:
        print(f"write_sealed_consts: {exc}", file=sys.stderr)
        return 2
    Path(args.out).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
